"""Measure how good the resume retriever actually is.

Any retriever returns *something*, so "it works" is not a claim worth making.
This script scores the pipeline against a labeled set and prints numbers that
can be reproduced, compared across changes, and defended if someone asks where
they came from.

Metrics:

recall@k
    Of the passages labeled relevant for a query, what fraction appear in the
    top k. This is the one that matters for the product: the suggestions can
    only be as good as the passages handed to the model, and a relevant bullet
    that never gets retrieved cannot be suggested.

MRR
    Mean reciprocal rank of the first relevant passage. 1.0 means the best
    passage was always ranked first. Recall says the right bullet was in the
    list; MRR says it was near the top, which is what the user reads.

A random-ordering baseline is reported alongside, because a metric with nothing
to compare against is not evidence. Run:

    pip install -r backend/requirements-rag.txt
    python eval/run_eval.py

Add --backend hashing to score the dependency-free embedder instead. It is
substantially worse, which is the point of having the real one.
"""

from __future__ import annotations

import argparse
import json
import os
import random
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "backend"))

# Settings validation runs at import time and refuses to boot without a key
# (CWE-798 fix). The eval never signs a token; this satisfies the validator.
os.environ.setdefault("SECRET_KEY", "eval-only-not-a-real-key-0123456789abcdef")
os.environ.setdefault("DATABASE_URL", "sqlite+aiosqlite:///./eval.db")

from app.rag.embeddings import get_embedder  # noqa: E402

DATASET_PATH = Path(__file__).parent / "dataset.json"
RESULTS_PATH = Path(__file__).parent / "results.md"
K_VALUES = (1, 3, 5)
# Fixed so the baseline is reproducible. A baseline that moved between runs
# would make every comparison against it meaningless.
BASELINE_SEED = 20260804


def cosine(left: list[float], right: list[float]) -> float:
    """Both embedders emit unit vectors, so a dot product is the cosine."""
    return sum(a * b for a, b in zip(left, right))


def score_ranking(ranked_ids: list[str], relevant: set[str]) -> dict:
    """recall@k for each k, plus the reciprocal rank of the first hit."""
    result = {
        f"recall@{k}": len(relevant & set(ranked_ids[:k])) / len(relevant)
        for k in K_VALUES
    }
    result["rr"] = next(
        (
            1.0 / rank
            for rank, chunk_id in enumerate(ranked_ids, start=1)
            if chunk_id in relevant
        ),
        0.0,
    )
    return result


def mean(values: list[float]) -> float:
    return sum(values) / len(values) if values else 0.0


def evaluate(dataset: dict, backend: str) -> tuple[dict, dict, list[dict]]:
    corpus = dataset["corpus"]
    queries = dataset["queries"]

    embedder = get_embedder(backend)
    # Embed the section heading with the text, exactly as the pipeline does.
    # Scoring a different representation than production uses would make the
    # number an interesting fact about this script and nothing else.
    corpus_vectors = embedder.embed(
        [f"{item['section']}: {item['text']}" for item in corpus]
    )
    query_vectors = embedder.embed([item["query"] for item in queries])

    rng = random.Random(BASELINE_SEED)
    per_query: list[dict] = []
    scores: list[dict] = []
    baselines: list[dict] = []

    for query, query_vector in zip(queries, query_vectors):
        relevant = set(query["relevant"])

        ranked = sorted(
            zip((item["id"] for item in corpus), corpus_vectors),
            key=lambda pair: cosine(query_vector, pair[1]),
            reverse=True,
        )
        ranked_ids = [chunk_id for chunk_id, _ in ranked]

        shuffled = [item["id"] for item in corpus]
        rng.shuffle(shuffled)

        result = score_ranking(ranked_ids, relevant)
        scores.append(result)
        baselines.append(score_ranking(shuffled, relevant))
        per_query.append(
            {
                "query": query["query"],
                "relevant": sorted(relevant),
                "top5": ranked_ids[:5],
                **result,
            }
        )

    def aggregate(rows: list[dict]) -> dict:
        summary = {f"recall@{k}": mean([r[f"recall@{k}"] for r in rows]) for k in K_VALUES}
        summary["mrr"] = mean([r["rr"] for r in rows])
        return summary

    return aggregate(scores), aggregate(baselines), per_query


def render(summary: dict, baseline: dict, per_query: list[dict], backend: str, n: int) -> str:
    lines = [
        "# Retrieval eval results",
        "",
        "Generated by `python eval/run_eval.py`. Regenerate after any change to",
        "the chunker, the embedder or the ranking, and commit the diff.",
        "",
        f"- Embedding backend: `{backend}`",
        f"- Corpus: {n} passages",
        f"- Queries: {len(per_query)} labeled job-description excerpts",
        "",
        "| Metric | Retriever | Random baseline |",
        "|---|---|---|",
    ]
    for k in K_VALUES:
        key = f"recall@{k}"
        lines.append(f"| {key} | {summary[key]:.3f} | {baseline[key]:.3f} |")
    lines.append(f"| MRR | {summary['mrr']:.3f} | {baseline['mrr']:.3f} |")

    lines += [
        "",
        "The random baseline ranks the same corpus in a fixed shuffled order. It is",
        "here so the retriever's numbers mean something: a recall figure with nothing",
        "to compare against is not evidence.",
        "",
        "## Per query",
        "",
        "| Query | Labeled relevant | Retrieved top 5 | recall@5 | RR |",
        "|---|---|---|---|---|",
    ]
    for row in per_query:
        query = row["query"][:70] + ("..." if len(row["query"]) > 70 else "")
        lines.append(
            f"| {query} | {', '.join(row['relevant'])} | {', '.join(row['top5'])} "
            f"| {row['recall@5']:.2f} | {row['rr']:.2f} |"
        )
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--backend",
        default="sentence-transformers",
        choices=["sentence-transformers", "hashing"],
        help="Embedding backend to score.",
    )
    parser.add_argument(
        "--write",
        action="store_true",
        help=f"Write the report to {RESULTS_PATH.name} as well as stdout.",
    )
    args = parser.parse_args()

    dataset = json.loads(DATASET_PATH.read_text(encoding="utf-8"))
    summary, baseline, per_query = evaluate(dataset, args.backend)
    report = render(summary, baseline, per_query, args.backend, len(dataset["corpus"]))

    print(report)
    if args.write:
        RESULTS_PATH.write_text(report, encoding="utf-8")
        print(f"wrote {RESULTS_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
